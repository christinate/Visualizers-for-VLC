export function ExpandPalette(palette) {
  // The first entry in the palette contains the background/companion color; 
  // zero it out.
  let palette_zeroed = structuredClone(palette);
  palette_zeroed[0] = 0.0;
  palette_zeroed[1] = 0.0;
  palette_zeroed[2] = 0.0;

  let ret = new Float32Array(256 * 4);
  for (let i = 0; i < 256; i++) {
    let s = i * (1.0 / 255.0);
    let color = SamplePalette(palette_zeroed, s);
    ret[i * 4 + 0] = color.r;
    ret[i * 4 + 1] = color.g;
    ret[i * 4 + 2] = color.b;
    ret[i * 4 + 3] = 1.0;
  }
  return ret;
}
